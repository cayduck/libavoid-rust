//
// reset() loads a fresh copy of the wasm-bindgen glue module, which
// instantiates a new wasm instance (see "Failure containment" in
// index.d.ts).

function loadInstance() {
  const glue = require.resolve("./pkg");
  delete require.cache[glue];
  return require(glue);
}

