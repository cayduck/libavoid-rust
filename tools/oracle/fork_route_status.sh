#!/usr/bin/env bash
# Golden output for tests/fork_route_status_oracle.rs: ConnRef::hasValidRoute()
# and ConnRef::hasCrossingObstacles(), which the port takes from the
# Adaptagrams fork that libavoid-js builds on (Aksem/adaptagrams).
#
#   tools/oracle/fork_route_status.sh [count]   (default 250 scenes)
#
# Builds a copy of the vendored upstream libavoid with the fork's two commits
# applied (tools/oracle/fork_route_status.patch; they add the two methods and
# a flag, and change no route), replays the scenes of
# fork_route_status_scenes.mjs through fork_route_status.cpp and writes
# tests/fork_route_status/golden.txt: each scene followed by a hash of its
# expected output per transaction.  The vendored sources are never modified.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HERE="$ROOT/tools/oracle"
VENDOR="${VENDOR:-$ROOT/vendor/adaptagrams/cola}"
BUILD="${FORK_STATUS_BUILD:-$ROOT/target/fork_route_status}"
COUNT="${1:-250}"
OUT="$ROOT/tests/fork_route_status/golden.txt"

mkdir -p "$BUILD/src/cola/libavoid" "$BUILD/obj"
cp "$VENDOR"/libavoid/*.cpp "$VENDOR"/libavoid/*.h "$BUILD/src/cola/libavoid/"
(cd "$BUILD/src" && patch -p1 -s --no-backup-if-mismatch < "$HERE/fork_route_status.patch")
F="-std=c++14 -O2 -ffp-contract=off -w -DNDEBUG -I$BUILD/src/cola"
for f in "$BUILD"/src/cola/libavoid/*.cpp; do
  g++ $F -c "$f" -o "$BUILD/obj/$(basename "${f%.cpp}").o" &
done
wait
g++ $F "$HERE/fork_route_status.cpp" "$BUILD"/obj/*.o -o "$BUILD/fork_route_status"

SCENES="$BUILD/scenes"
mkdir -p "$SCENES"
find "$SCENES" -name '*.txt' -delete
node "$HERE/fork_route_status_scenes.mjs" "$SCENES" 1 "$COUNT"

# Each transaction's output is stored as a hash (tools/oracle/golden_hash.mjs);
# FULL=1 writes the output itself instead, to see where a test differs.
digest() { if [ "${FULL:-0}" = 1 ]; then cat; else node "$HERE/golden_hash.mjs"; fi; }

mkdir -p "$(dirname "$OUT")"
{
  echo "# Generated by tools/oracle/fork_route_status.sh; do not edit."
  for f in "$SCENES"/*.txt; do
    echo "scene $(basename "$f" .txt)"
    cat "$f"
    echo "expect"
    timeout 120 "$BUILD/fork_route_status" "$f" | digest
    echo "end"
  done
} > "$OUT"
echo "wrote $OUT ($COUNT scenes)"
