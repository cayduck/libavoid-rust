#!/usr/bin/env python3
"""Generates the API-coverage audit scenes `tests/audit_scenes/audit_NNN.ops`.

    tools/oracle/audit_scenes.py [COUNT]      (default 160)

The scenes are op scripts in the fixture DSL (tools/fixtures/convert.py,
interpreter tests/common/fixture_ops.rs) that exercise public API the
upstream fixtures and the other oracles rarely reach: every router flag
(PartialTime, SimpleRouting, ClusteredRouting, IgnoreRegions,
UseLeesAlgorithm, InvisibilityGrph, SelectiveReroute, PartialFeedback,
RubberBandRouting), all routing options, routing parameters at 0 /
negative (sensible default) / large values, both transaction modes,
poly-line + orthogonal + mixed routers, clusters, checkpoints, pins with
costs and exclusivity, junctions, ConnRef::setEndpoint / setFixedRoute /
setFixedExistingRoute / clearFixedRoute / setHateCrossings /
splitAtSegment, ShapeRef::setCentrePos, Router::moveShape (both overloads,
first_move), markAllObstaclesAsMoved, moveJunction, deletions in random
order, removeJunctionAndMergeConnectors and hyperedge rerouting.  Every
transaction is followed by an outputDiagram() dump.

Only input with defined upstream behaviour is generated (no API misuse:
e.g. with transactions off nothing that has attached connectors is moved
and no obstacle with pins is deleted, both of which crash upstream).

tools/oracle/audit_scenes.sh runs every scene through the real C++ (NDEBUG,
bump allocator) to produce the goldens; tests/audit_scenes.rs replays them
through the port.  Deterministic (fixed seed).
"""

import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "tests", "audit_scenes")

PARAMS = 9   # RoutingParameter count
OPTIONS = 7  # RoutingOption count
FLAGS = 9    # setRouterFlag codes (see convert.py ROUTER_FLAGS)


def num(v):
    return repr(float(v)) if not float(v).is_integer() else str(int(v))


class Scene:
    def __init__(self, idx, rng):
        self.idx = idx
        self.rng = rng
        self.lines = []
        self.out = 0
        self.var = 0
        self.shapes = []      # (var, x1, y1, x2, y2, has_pins, pin_classes)
        self.junctions = []   # (var, x, y)
        self.conns = []       # (var, src_kind, dst_kind)
        self.clusters = []
        self.pins = []

    def v(self, prefix):
        self.var += 1
        return "%s%d" % (prefix, self.var)

    def emit(self, s):
        self.lines.append(s)

    def output(self):
        self.out += 1
        self.emit("output router audit_%03d-%d" % (self.idx, self.out))

    def process(self):
        self.emit("do (processTransaction router)")
        self.output()


def gen(idx, rng):
    sc = Scene(idx, rng)
    e = sc.emit
    e("# Generated by tools/oracle/audit_scenes.py (seeded).  Do not edit.")
    e("fixture audit_%03d" % idx)
    e("mode golden")
    flags = rng.choice([1, 2, 3, 2, 3])
    e("let router router (Router %d)" % flags)
    poly_allowed = flags & 1
    orth_allowed = flags & 2
    transactions = rng.random() < 0.75
    if not transactions:
        e("do (setTransactionUse router false)")

    # Router flags.
    rubber = False
    if poly_allowed and not orth_allowed and transactions and rng.random() < 0.25:
        rubber = True
        e("do (setRouterFlag router 3 true)")
        e("do (setRouterFlag router 8 true)")
    for code in (0, 2, 4, 5, 6, 7):
        if rng.random() < 0.2:
            e("do (setRouterFlag router %d %s)" % (code, rng.choice(["true", "false"])))
    if not rubber and rng.random() < 0.1:
        e("do (setRouterFlag router 3 true)")

    # Parameters and options.
    for p in range(PARAMS):
        r = rng.random()
        if r < 0.15:
            val = 0
        elif r < 0.3:
            val = -1
        elif r < 0.45:
            val = rng.choice([1, 5, 10, 50, 200, 4000])
        else:
            continue
        if p == 0 and val == 0 and orth_allowed and rng.random() < 0.5:
            val = 10
        e("do (setRoutingParameter router %d %s)" % (p, num(val)))
    for o in range(OPTIONS):
        if rng.random() < 0.35:
            e("do (setRoutingOption router %d %s)" % (o, rng.choice(["true", "false"])))

    # Shapes on a coarse grid (sometimes touching/overlapping, sometimes
    # zero-size).
    nshapes = rng.randint(1, 7)
    for _ in range(nshapes):
        x = rng.randint(0, 12) * 25
        y = rng.randint(0, 12) * 25
        w = rng.choice([0, 10, 20, 25, 30, 50, 60]) if rng.random() < 0.15 else rng.choice([20, 25, 30, 50, 60])
        h = rng.choice([20, 25, 30, 50, 60])
        rv = sc.v("rect")
        sv = sc.v("shape")
        e("let %s poly (Rectangle (Point %d %d) (Point %d %d))" % (rv, x, y, x + w, y + h))
        e("let %s shape (ShapeRef router %s 0)" % (sv, rv))
        classes = []
        if transactions and w > 0 and rng.random() < 0.5:
            for _ in range(rng.randint(1, 3)):
                cls = rng.randint(1, 3)
                pv = sc.v("pin")
                xo = rng.choice([0, 0.25, 0.5, 1])
                yo = rng.choice([0, 0.5, 0.75, 1])
                vis = rng.choice([15, 1, 2, 4, 8, 3, 12, 0])
                e("let %s pin (Pin %s %d %s %s true %s %d)" % (pv, sv, cls, num(xo), num(yo),
                                                              num(rng.choice([0, 0, 5])), vis))
                if rng.random() < 0.3:
                    e("do (setExclusive %s false)" % pv)
                if rng.random() < 0.3:
                    e("do (setConnectionCost %s %s)" % (pv, num(rng.choice([0, 1, 20]))))
                classes.append(cls)
                sc.pins.append(pv)
        sc.shapes.append([sv, x, y, x + w, y + h, bool(classes), classes, rv])

    if transactions and rng.random() < 0.4:
        for _ in range(rng.randint(1, 2)):
            jv = sc.v("junction")
            x, y = rng.randint(0, 12) * 25 + 12, rng.randint(0, 12) * 25 + 12
            e("let %s junction (JunctionRef router (Point %d %d) 0)" % (jv, x, y))
            if rng.random() < 0.3:
                e("do (setPositionFixed %s true)" % jv)
            if rng.random() < 0.3:
                e("do (preferOrthogonalDimension %s %d)" % (jv, rng.randint(0, 1)))
            sc.junctions.append(jv)

    if rng.random() < 0.2:
        cv = sc.v("cluster")
        rv = sc.v("crect")
        x, y = rng.randint(0, 6) * 25, rng.randint(0, 6) * 25
        e("let %s poly (Rectangle (Point %d %d) (Point %d %d))" % (rv, x, y, x + 150, y + 125))
        e("let %s cluster (ClusterRef router %s 0)" % (cv, rv))
        sc.clusters.append(cv)

    def free_point():
        return "(Point %d %d)" % (rng.randint(-2, 14) * 25 + rng.choice([0, 5]),
                                  rng.randint(-2, 14) * 25 + rng.choice([0, 7]))

    def connend():
        r = rng.random()
        pinned = [s for s in sc.shapes if s[6]]
        if r < 0.3 and pinned:
            s = rng.choice(pinned)
            return "(ConnEndShape %s %d)" % (s[0], rng.choice(s[6])), "pin"
        if r < 0.45 and sc.junctions:
            return "(ConnEndJunction %s)" % rng.choice(sc.junctions), "junction"
        if rng.random() < 0.4:
            return "(ConnEndPt %s %d)" % (free_point(), rng.choice([15, 1, 2, 4, 8, 5, 10])), "point"
        return "(ConnEndPt1 %s)" % free_point(), "point"

    nconns = rng.randint(1, 7)
    for _ in range(nconns):
        cv = sc.v("conn")
        (s, sk), (d, dk) = connend(), connend()
        if transactions:
            e("let %s conn (ConnRefEnds router %s %s 0)" % (cv, s, d))
        else:
            # ConnRef(router, src, dst) with transactions off routes before
            # registering its reroute flag; upstream then crashes in
            # EdgeInf::alertConns() (null flag; the port registers it first).
            e("let %s conn (ConnRef router 0)" % cv)
            e("do (setEndpoints %s %s %s)" % (cv, s, d))
        if poly_allowed and orth_allowed:
            e("do (setRoutingType %s %d)" % (cv, rng.choice([1, 2])))
        if rng.random() < 0.2:
            e("do (setHateCrossings %s true)" % cv)
        if rng.random() < 0.2 and not rubber:
            n = rng.randint(1, 2)
            cps = sc.v("cps")
            e("let %s checkpoints (Checkpoints %d)" % (cps, n))
            for k in range(n):
                if rng.random() < 0.5:
                    e("set (at %s %d) (Checkpoint %s)" % (cps, k, free_point()))
                else:
                    e("set (at %s %d) (CheckpointDirs %s %d %d)" % (cps, k, free_point(),
                                                                    rng.choice([15, 1, 2, 4, 8]),
                                                                    rng.choice([15, 1, 2, 4, 8])))
            e("do (setRoutingCheckpoints %s %s)" % (cv, cps))
        sc.conns.append([cv, sk, dk])
    sc.process()

    # Mutation steps.
    for _step in range(rng.randint(1, 5)):
        for _k in range(rng.randint(1, 3)):
            r = rng.random()
            attached_free = lambda s: not s[5]
            if r < 0.15 and sc.shapes:
                s = rng.choice(sc.shapes)
                if transactions or not (s[5] or sc.conns):
                    e("do (moveShape router %s %d %d)" % (s[0], rng.randint(-3, 3) * 10, rng.randint(-3, 3) * 10))
            elif r < 0.25 and sc.shapes:
                s = rng.choice(sc.shapes)
                if transactions:
                    dx, dy = rng.randint(-2, 2) * 25, rng.randint(-2, 2) * 25
                    nv = sc.v("np")
                    e("let %s poly (Rectangle (Point %d %d) (Point %d %d))" % (nv, s[1] + dx, s[2] + dy,
                                                                             s[3] + dx, s[4] + dy))
                    e("do (moveShapePoly router %s %s %s)" % (s[0], nv, rng.choice(["true", "false"])))
            elif r < 0.3 and transactions and sc.shapes:
                s = rng.choice(sc.shapes)
                e("do (setCentrePos %s (Point %d %d))" % (s[0], rng.randint(0, 12) * 25, rng.randint(0, 12) * 25))
            elif r < 0.35 and transactions:
                e("do (markAllObstaclesAsMoved router)")
            elif r < 0.42 and transactions and sc.junctions:
                j = rng.choice(sc.junctions)
                e("do (moveJunction router %s %d %d)" % (j, rng.randint(-2, 2) * 10, rng.randint(-2, 2) * 10))
            elif r < 0.5 and sc.conns:
                c = rng.choice(sc.conns)
                s, k = connend()
                e("do (setEndpoint %s %d %s)" % (c[0], rng.choice([1, 2]), s))
            elif r < 0.55 and sc.conns:
                c = rng.choice(sc.conns)
                fp = sc.v("fr")
                n = rng.randint(2, 4)
                e("let %s poly (Polygon %d)" % (fp, n))
                for k in range(n):
                    e("set (ps %s %d) %s" % (fp, k, free_point()))
                e("do (setFixedRoute %s %s)" % (c[0], fp))
            elif r < 0.6 and sc.conns:
                c = rng.choice(sc.conns)
                e("do (setFixedExistingRoute %s)" % c[0])
            elif r < 0.65 and sc.conns:
                c = rng.choice(sc.conns)
                e("do (clearFixedRoute %s)" % c[0])
            elif r < 0.7 and sc.conns:
                c = rng.choice(sc.conns)
                e("do (setHateCrossings %s %s)" % (c[0], rng.choice(["true", "false"])))
            elif r < 0.75 and sc.conns and transactions:
                c = rng.choice(sc.conns)
                e("do (deleteConnector router %s)" % c[0])
                sc.conns.remove(c)
            elif r < 0.8 and sc.shapes:
                s = rng.choice(sc.shapes)
                if transactions or not s[5]:
                    e("do (deleteShape router %s)" % s[0])
                    sc.shapes.remove(s)
                    # ConnEnds attached to it become free points.
            elif r < 0.84 and sc.clusters:
                cl = sc.clusters[0]
                nv = sc.v("cnp")
                x, y = rng.randint(0, 6) * 25, rng.randint(0, 6) * 25
                e("let %s poly (Rectangle (Point %d %d) (Point %d %d))" % (nv, x, y, x + 125, y + 100))
                e("do (clusterSetNewPoly %s %s)" % (cl, nv))
            elif r < 0.86 and sc.clusters:
                e("do (deleteCluster router %s)" % sc.clusters.pop())
            elif r < 0.9 and sc.junctions and transactions and rng.random() < 0.5:
                j = sc.junctions.pop(rng.randrange(len(sc.junctions)))
                e("do (deleteJunction router %s)" % j)
            elif r < 0.95 and transactions:
                for o in range(OPTIONS):
                    if rng.random() < 0.3:
                        e("do (setRoutingOption router %d %s)" % (o, rng.choice(["true", "false"])))
                if rng.random() < 0.5:
                    e("do (setRoutingParameter router %d %s)" % (rng.randrange(PARAMS),
                                                                  num(rng.choice([0, -1, 2, 30]))))
        sc.process()

    e("delete router audit_%03d-final" % idx)
    e("ret 0")
    return "\n".join(sc.lines) + "\n"


def main():
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 160
    os.makedirs(OUT, exist_ok=True)
    rng = random.Random(0xA0D17)
    for i in range(count):
        text = gen(i, rng)
        with open(os.path.join(OUT, "audit_%03d.ops" % i), "w") as f:
            f.write(text)
    print("wrote %d scenes to %s" % (count, OUT))


if __name__ == "__main__":
    main()
