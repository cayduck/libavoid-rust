#!/usr/bin/env bash
# Golden output for tests/reroute_after_edits_oracle.rs: Router::set_reroute_after_edits(),
# which the port takes from the Adaptagrams fork that libavoid-js builds on.
#
#   tools/oracle/reroute_after_edits.sh [count]   (default 200 scenes)
#
# Builds tools/libavoid-js-compare/driver.cpp twice: against a copy of the
# vendored upstream libavoid (the option off) and against a copy with
# tools/oracle/reroute_after_edits.patch applied (the option on). Replays the
# scenes of reroute_after_edits_scenes.mjs through both and writes
# tests/reroute_after_edits/golden.txt: each scene followed by a hash of the
# routes after every transaction, off and on. The vendored sources are never
# modified.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HERE="$ROOT/tools/oracle"
VENDOR="${VENDOR:-$ROOT/vendor/adaptagrams/cola}"
BUILD="${REROUTE_BUILD:-$ROOT/target/reroute_after_edits}"
COUNT="${1:-200}"
OUT="$ROOT/tests/reroute_after_edits/golden.txt"

build() { # <variant> <apply patch: 0|1>
  local d="$BUILD/$1"
  mkdir -p "$d/src/cola/libavoid" "$d/obj"
  cp "$VENDOR"/libavoid/*.cpp "$VENDOR"/libavoid/*.h "$d/src/cola/libavoid/"
  if [ "$2" = 1 ]; then
    (cd "$d/src" && patch -p1 -s --no-backup-if-mismatch < "$HERE/reroute_after_edits.patch")
  fi
  local F="-std=c++14 -O2 -ffp-contract=off -w -DNDEBUG -I$d/src/cola" f
  for f in "$d"/src/cola/libavoid/*.cpp; do
    g++ $F -c "$f" -o "$d/obj/$(basename "${f%.cpp}").o" &
  done
  wait
  g++ $F "$ROOT/tools/libavoid-js-compare/driver.cpp" "$d"/obj/*.o -o "$d/driver"
}
build off 0
build on 1

SCENES="$BUILD/scenes"
mkdir -p "$SCENES"
find "$SCENES" -name '*.txt' -delete
node "$HERE/reroute_after_edits_scenes.mjs" "$SCENES" 1 "$COUNT"

# Each transaction's output is stored as a hash (tools/oracle/golden_hash.mjs);
# FULL=1 writes the output itself instead, to see where a test differs.
digest() { if [ "${FULL:-0}" = 1 ]; then cat; else node "$HERE/golden_hash.mjs"; fi; }

mkdir -p "$(dirname "$OUT")"
{
  echo "# Generated by tools/oracle/reroute_after_edits.sh; do not edit."
  for f in "$SCENES"/*.txt; do
    echo "scene $(basename "$f" .txt)"
    cat "$f"
    echo "expect off"
    timeout 120 "$BUILD/off/driver" "$f" 2>/dev/null | digest
    echo "expect on"
    timeout 120 "$BUILD/on/driver" "$f" 2>/dev/null | digest
    echo "end"
  done
} > "$OUT"
echo "wrote $OUT ($COUNT scenes)"
