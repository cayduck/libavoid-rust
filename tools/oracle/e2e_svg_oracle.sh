#!/usr/bin/env bash
# Records upstream's SVG debug output -- Router::outputInstanceToSVG() and
# Router::outputDiagramSVG() -- after every transaction of the committed
# end-to-end fuzz scenes (tests/golden/e2e_fuzz.txt) for
# tests/e2e_svg_oracle.rs.
#
#   tools/oracle/e2e_svg_oracle.sh
#
# Uses the NDEBUG build of the fuzz driver (tools/oracle/e2e_fuzz_build.sh;
# in a worktree pass VENDOR=<main checkout>/vendor/adaptagrams/cola) with
# E2E_SVG=1, which appends "V <fnv> <bytes>" (outputInstanceToSVG()) and
# "W <fnv> <bytes>" (outputDiagramSVG()) to every transaction dump, and
# E2E_FULL=1 (no per-stage hashing).  Scenes marked #exclude in the golden
# (upstream undefined) are skipped.  A scene is recorded only if the rest of
# its output still equals the committed golden, i.e. the run is the one the
# port is already compared with.
#
# Output: tests/golden-svg/e2e-svg.txt, one line per scene:
#   <scene> <sha256 of its V/W lines, each followed by "\n"> <V/W line count>
# Env: E2E_SVG_TIMEOUT (seconds per scene, default 60).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
BIN="${E2E_BIN:-$ROOT/target/e2e_fuzz/ndebug/e2e_fuzz}"
WORK="$ROOT/target/e2e-svg-oracle"
mkdir -p "$WORK"
[ -x "$BIN" ] || { echo "build the fuzz driver first (tools/oracle/e2e_fuzz_build.sh)"; exit 2; }

python3 - "$ROOT/tests/golden/e2e_fuzz.txt" "$WORK/scenes.txt" <<'PY'
import sys
out = open(sys.argv[2], "w")
cur = []; state = None; first_out = None
for line in open(sys.argv[1]):
    line = line.rstrip("\n")
    if line.startswith("#scene "):
        cur = [line]; state = "dsl"; first_out = None
    elif line == "#out":
        state = "out"
    elif line == "#end":
        if first_out is None or not first_out.startswith("#exclude"):
            out.write("\n".join(cur) + "\n#out\n#end\n")
        state = None
    elif state == "dsl":
        cur.append(line)
    elif state == "out" and first_out is None:
        first_out = line
PY

# (The driver caps each scene's child process at E2E_RSS_MB, default 4096.)
(cd "$WORK" && E2E_SVG=1 E2E_FULL=1 E2E_TIMEOUT="${E2E_SVG_TIMEOUT:-60}" \
    timeout 7200 "$BIN" run "$WORK/scenes.txt" > "$WORK/out.txt")

python3 - "$ROOT/tests/golden/e2e_fuzz.txt" "$WORK/out.txt" "$ROOT/tests/golden-svg/e2e-svg.txt" <<'PY'
import hashlib, sys
def scenes(path):
    res = {}; name = None; state = None
    for line in open(path):
        line = line.rstrip("\n")
        if line.startswith("#scene "):
            name = line[7:]; res[name] = []; state = "dsl"
        elif line == "#out":
            state = "out"
        elif line == "#end":
            state = None
        elif state == "out":
            res[name].append(line)
    return res
golden, got = scenes(sys.argv[1]), scenes(sys.argv[2])
def fnv(lines):
    h = 1469598103934665603
    for s in lines:
        for b in s.encode():
            h ^= b; h = (h * 1099511628211) & 0xffffffffffffffff
        h ^= 10; h = (h * 1099511628211) & 0xffffffffffffffff
    return h
ok = differ = 0
with open(sys.argv[3], "w") as f:
    f.write("# Generated by tools/oracle/e2e_svg_oracle.sh: per e2e fuzz scene, the sha256\n")
    f.write("# of the C++ driver's E2E_SVG lines (outputInstanceToSVG()/outputDiagramSVG()\n")
    f.write("# after every transaction, each \"V|W <fnv> <bytes>\\n\") and their count.\n")
    for name in sorted(got, key=lambda n: (int(n.split("-")[0][1:]), int(n.split("-")[1]))):
        lines = got[name]
        svg = [l for l in lines if l.startswith("V ") or l.startswith("W ")]
        rest = [l for l in lines if not (l.startswith("V ") or l.startswith("W "))]
        # The committed golden hashes large scenes per stage; rebuild that form.
        exp = golden[name]
        if exp and exp[0].startswith("#assert"):
            exp = exp[1:]
        pre, stages = [], []
        for l in rest:
            if l.startswith("T "):
                stages.append([l])
            elif stages:
                stages[-1].append(l)
            else:
                pre.append(l)
        if sum(len(s) for s in stages) > 400:
            rest = pre + ["%s lines=%d fnv=%016x" % (s[0], len(s), fnv(s)) for s in stages]
        if rest != exp or not svg:
            differ += 1
            print("skip %s (C++ output differs from the committed golden or has no stages)" % name)
            continue
        data = "".join(l + "\n" for l in svg).encode()
        f.write("%s %s %d\n" % (name, hashlib.sha256(data).hexdigest(), len(svg)))
        ok += 1
print("e2e svg oracle: %d scenes recorded, %d skipped" % (ok, differ))
PY
