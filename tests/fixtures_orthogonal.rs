type CallbackLog = Rc<RefCell<Vec<ConnIdx>>>;

fn recorder(log: &CallbackLog) -> Option<Box<dyn FnMut(ConnIdx)>> {
    let log = log.clone();
    Some(Box::new(move |c| log.borrow_mut().push(c)))
}

/// Upstream `connCallback()` of multiconnact.cpp applied to the callbacks
/// recorded during the last transaction (Rust callbacks cannot borrow the
/// router; the display route does not change after the callbacks of a
/// transaction run).
fn flush_callbacks(router: &mut Router, log: &CallbackLog, out: &mut String) {
    let conns: Vec<ConnIdx> = log.borrow_mut().drain(..).collect();
    for conn_ref in conns {
        out.push_str(&format!("Connector {} needs rerouting!\n", conn_ref.id(router)));
        let route = conn_ref.display_route(router).clone();
        out.push_str("New path: ");
        for i in 0..route.ps.len() {
            out.push_str(&format!(
                "{}({}, {})",
                if i > 0 { "-" } else { "" },
                printf_f(route.ps[i].x),
                printf_f(route.ps[i].y)
            ));
        }
        out.push('\n');
    }
}

// upstream: tests/multiconnact.cpp
#[test]
fn multiconnact() {
    let mut out = String::new();
    let log: CallbackLog = Rc::default();
    let mut router = Router::new(ORTHOGONAL_ROUTING);

    let src_pt = pt(0.0, 400.0);
    let dst_pt = pt(775.0, 400.0);
    let conn_ref = ConnRef::new_with_ends(&mut router, &ConnEnd::from_point(src_pt), &ConnEnd::from_point(dst_pt), 0);
    conn_ref.set_callback(&mut router, recorder(&log));

    let src_pt2 = pt(775.0, 625.0);
    let dst_pt2 = pt(350.0, 475.0);
    let conn_ref2 = ConnRef::new_with_ends(&mut router, &ConnEnd::from_point(src_pt2), &ConnEnd::from_point(dst_pt2), 0);
    conn_ref2.set_callback(&mut router, recorder(&log));

    router.process_transaction();
    flush_callbacks(&mut router, &log, &mut out);

    out.push_str("\nShifting endpoint.\n");
    conn_ref.set_endpoints(&mut router, &ConnEnd::from_point(pt(0.0, 375.0)), &ConnEnd::from_point(pt(775.0, 400.0)));
    conn_ref2.set_endpoints(&mut router, &ConnEnd::from_point(pt(775.0, 625.0)), &ConnEnd::from_point(pt(350.0, 450.0)));
    router.process_transaction();
    flush_callbacks(&mut router, &log, &mut out);

    out.push_str("\nShifting endpoint.\n");
    conn_ref.set_endpoints(&mut router, &ConnEnd::from_point(pt(0.0, 400.0)), &ConnEnd::from_point(pt(775.0, 400.0)));
    conn_ref2.set_endpoints(&mut router, &ConnEnd::from_point(pt(775.0, 625.0)), &ConnEnd::from_point(pt(350.0, 475.0)));
    router.process_transaction();
    flush_callbacks(&mut router, &log, &mut out);

    assert_matches_golden_bump(&mut router, "multiconnact-final");
    router.destruct();
    assert_eq!(out, read_golden_file_in(GoldenDir::Bump, "multiconnact", "stdout"));
    assert_eq!(exit_code("multiconnact"), 0);
}

